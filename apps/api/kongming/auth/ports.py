"""auth 域持久化和外存端口,以 Protocol 隔离用例层与具体实现。

service 只依赖这些接口;SQLAlchemy 实现在 repository.py、Redis 实现在 stores.py。
UnitOfWork 聚合 repo 并承载 commit/rollback,service 不直接操作 Session。
"""

from __future__ import annotations

from typing import TYPE_CHECKING, Protocol

from kongming.auth.models import NormalizedProfile, Role, Tenant, User

if TYPE_CHECKING:
    from kongming.config import Settings


class UserRepo(Protocol):
    async def get_by_username(self, username: str) -> User | None: ...
    async def get_by_id(self, user_id: str) -> User | None: ...
    async def get_by_email(self, email: str) -> User | None: ...
    async def create(self, user: User) -> None: ...
    async def update_password(self, user_id: str, password_hash: str) -> None: ...
    async def touch_last_login(self, user_id: str) -> None: ...


class RoleRepo(Protocol):
    async def get_by_key(self, role_key: str) -> Role | None: ...
    async def insert(self, role: Role) -> None: ...
    async def list_role_keys(self, user_id: str) -> list[str]: ...
    async def bind_user(self, user_id: str, role_id: str) -> None: ...
    async def bind_perm_codes(self, role_id: str, perm_codes: list[str]) -> None:
        """增量补齐角色-权限点绑定(只增不改,幂等)。"""
        ...


class TenantRepo(Protocol):
    async def get_by_key(self, tenant_key: str) -> Tenant | None: ...
    async def insert(self, tenant: Tenant) -> None: ...
    async def list_for_user(self, user_id: str) -> list[Tenant]: ...
    async def bind_user(self, user_id: str, tenant_id: str) -> None: ...


class PermRepo(Protocol):
    async def list_codes(self, user_id: str) -> list[str]: ...
    async def insert_missing(self, perms: list[tuple[str, str, int]]) -> None:
        """按 (perm_code, perm_name, sort) 查缺补插(权限点=代码契约数据)。"""
        ...


class IdentityRepo(Protocol):
    async def find_user_id(self, provider: str, external_id: str) -> str | None: ...
    async def create(self, user_id: str, provider: str, external_id: str) -> None: ...


class OperLogRepo(Protocol):
    async def add(
        self, user_id: str | None, action: str, target: str | None, detail: dict[str, object]
    ) -> None: ...


class UnitOfWork(Protocol):
    users: UserRepo
    roles: RoleRepo
    tenants: TenantRepo
    perms: PermRepo
    identities: IdentityRepo
    operlog: OperLogRepo

    async def commit(self) -> None: ...
    async def rollback(self) -> None: ...


class RefreshFamilyStore(Protocol):
    """refresh 家族三态(D2):活跃票 / 墓碑(复用检测)/ 家族吊销标记。"""

    async def issue(self, user_id: str, fid: str, jti: str, ttl_sec: int) -> None: ...
    async def consume(self, jti: str, ttl_sec: int) -> tuple[str | None, str | None]:
        """原子消费活跃票并立墓碑。返回 (rotated_fid, tomb_fid):
        消费成功=(fid, None);命中墓碑=复用=(None, fid);两皆无=过期/伪造。"""
        ...

    async def is_revoked_family(self, fid: str) -> bool: ...
    async def revoke_family(self, fid: str, ttl_sec: int) -> None: ...
    async def revoke_all_user_families(self, user_id: str, ttl_sec: int) -> None: ...


class LoginAttemptStore(Protocol):
    async def incr_fails(self, username: str, window_sec: int) -> int: ...
    async def clear_fails(self, username: str) -> None: ...
    async def lock(self, username: str, lock_sec: int) -> None: ...
    async def locked_ttl(self, username: str) -> int:
        """锁剩余秒数,未锁返回 0。"""
        ...


class OAuthStateStore(Protocol):
    async def put(
        self, state: str, *, provider: str, code_verifier: str | None, ttl_sec: int
    ) -> None: ...
    async def take(self, state: str) -> dict[str, str] | None:
        """一次性取出并销毁(GETDEL);不存在/过期返回 None。"""
        ...


class OAuthProvider(Protocol):
    """provider 插件契约(ADR-006):声明式端点 + profile 归一化。"""

    key: str  # 注册表键(小写,路由路径段)
    display_name: str
    pkce: bool

    def configured(self, s: Settings) -> bool: ...
    def authorize_url(self, s: Settings, *, state: str, code_challenge: str | None) -> str: ...
    async def fetch_profile(
        self, s: Settings, *, code: str, code_verifier: str | None
    ) -> NormalizedProfile: ...
