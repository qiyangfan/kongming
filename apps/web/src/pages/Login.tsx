const PROVIDER_MARKS: Record<string, React.ComponentType<React.SVGProps<SVGSVGElement>>> = {
  github: simpleMark(siGithub),
  google: simpleMark(siGoogle),
  wecom: simpleMark(siWechat), // simple-icons 无企业微信独立图标,微信官方族图标代位
  dingtalk: DingtalkMark,
  feishu: FeishuMark,
};

export default function Login() {
  const navigate = useNavigate();
  const acceptTokens = useAuth((s) => s.acceptTokens);
  const [username, setUsername] = useState("");
  const [password, setPassword] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [pending, setPending] = useState(false);
  const [providers, setProviders] = useState<OptionsOut["providers"]>([]);

  useEffect(() => {
    // options 拉取失败不阻断账密登录(联邦入口整体隐藏)
    api
      .get<OptionsOut>("/auth/options")
      .then((o) => setProviders(o.providers))
      .catch(() => setProviders([]));
  }, []);

  async function submit(e: React.FormEvent) {
    e.preventDefault();
    setPending(true);
    setError(null);
    try {
      const pair = await api.post<TokenPairOut>("/auth/login", {
        username,
        password,
      });
      await acceptTokens(pair);
      navigate("/", { replace: true });
    } catch (err) {
      setError(err instanceof Error ? humanizeErrorText(err.message) : "登录失败");
    } finally {
      setPending(false);
    }
  }

  async function federatedLogin(provider: string, displayName: string) {
    setError(null);
    try {
      const { authorize_url } = await api.get<StartOut>(`/auth/${provider}/start`);
      window.location.href = authorize_url;
    } catch (err) {
      setError(
        err instanceof Error
          ? humanizeErrorText(err.message)
          : `${displayName} 登录未完成,请稍后再试`,
      );
    }
  }

  return (
    <div className="flex min-h-screen items-center justify-center bg-gradient-to-br from-grad-from via-grad-mid to-grad-end">
      <Card className="w-full max-w-sm">
        <CardHeader>
          <CardTitle>孔明 Kongming</CardTitle>
          <CardDescription>问计于数据,如问计于孔明</CardDescription>
        </CardHeader>
        <CardContent className="space-y-4">
          <form onSubmit={submit} className="space-y-4">
            <div className="space-y-2">
              <Label htmlFor="username">用户名</Label>
              <Input
                id="username"
                value={username}
                onChange={(e) => setUsername(e.target.value)}
                autoComplete="username"
                placeholder="请输入用户名"
              />
            </div>
            <div className="space-y-2">
              <Label htmlFor="password">密码</Label>
              <Input
                id="password"
                type="password"
                value={password}
                onChange={(e) => setPassword(e.target.value)}
                autoComplete="current-password"
                placeholder="请输入密码"
              />
            </div>
            {error && (
              <p className="text-sm text-destructive" role="alert">
                {error}
              </p>
            )}
            <Button type="submit" disabled={pending} className="w-full">
              {pending ? "登录中…" : "登录"}
            </Button>
          </form>

          {providers.length > 0 && (
            <>
              <div className="flex items-center gap-3 text-xs text-muted-foreground">
                <span className="h-px flex-1 bg-border" />或
                <span className="h-px flex-1 bg-border" />
              </div>
              <div className="space-y-2">
                {providers.map((p) => {
                  const Mark = PROVIDER_MARKS[p.provider];
                  return (
                    <Button
                      key={p.provider}
                      variant="outline"
                      className="w-full"
                      onClick={() => void federatedLogin(p.provider, p.display_name)}
                    >
                      {Mark && <Mark />}
                      使用 {p.display_name} 继续
                    </Button>
                  );
                })}
              </div>
            </>
          )}
        </CardContent>
      </Card>
    </div>
  );
}
